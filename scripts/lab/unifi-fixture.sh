#!/usr/bin/env bash
# L1 UniFi fixture: a disposable, self-hosted UniFi Network Application on THIS workstation, so the
# infrastructure/environments/homelab/unifi root can be planned and applied before it goes near the
# real UDM Pro (docs/PROJECT-PLAN.md Phase 3; docs/lab.md).
#
# Two containers on a private docker network, both named lab-unifi*:
#   lab-unifi        linuxserver/unifi-network-application (pinned tag@digest, memory-capped)
#   lab-unifi-mongo  mongo (pinned tag@digest, memory-capped, auth on, no published port)
# The controller's HTTPS port is published on 127.0.0.1 ONLY (default 18443). Nothing else is exposed.
#
# `up` also finishes first-run setup through the controller's own setup API (it creates the local
# admin; the default site already exists), so there is no wizard to click through. It then seeds,
# OUTSIDE of tofu, the objects the real controller already has and the root must only read or take
# over: the `server` network (VLAN 4, 10.10.0.0/16) and two known clients with fake, locally
# administered MACs (FIXTURE_HOST_MACS below; never a real MAC). Seeding is idempotent. Random credentials
# are written to talos/out/lab-unifi/ (gitignored, mode 700/600) and never to a tracked file.
#
# Only containers, the network and the volumes named lab-unifi* are ever created or removed here.
# The user's other containers are never touched.
#
# Usage:
#   scripts/lab/unifi-fixture.sh up        # create (or restart) the fixture and wait until it is ready
#   scripts/lab/unifi-fixture.sh status
#   scripts/lab/unifi-fixture.sh stop      # stop the containers, keep the data (frees RAM)
#   scripts/lab/unifi-fixture.sh down      # remove containers, network, volumes and credentials
#
# Env: LAB_UNIFI_PORT (default 18443), LAB_UNIFI_DIR (default talos/out/lab-unifi),
#      LAB_UNIFI_MEM (default 1536m), LAB_UNIFI_MONGO_MEM (default 512m)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

# Pins: keep in step with versions.yaml (lab_fixture_images).
UNIFI_IMAGE="linuxserver/unifi-network-application:10.6.106-ls150@sha256:4d5fc889c2f2c2cecc6b35d4d641780cbedbe90d3a51b8f03283261b137af468"
MONGO_IMAGE="mongo:8.0.34@sha256:4a4ab5d4834207389e0d7270fac988e21ffedccecba77991a552f755df229907"

PORT="${LAB_UNIFI_PORT:-18443}"
OUT_DIR="${LAB_UNIFI_DIR:-$REPO_ROOT/talos/out/lab-unifi}"
MEM="${LAB_UNIFI_MEM:-1536m}"
MONGO_MEM="${LAB_UNIFI_MONGO_MEM:-512m}"
NAME="lab-unifi"
MONGO_NAME="lab-unifi-mongo"
NET="lab-unifi"
VOL_CONFIG="lab-unifi-config"
VOL_MONGO="lab-unifi-mongo"
URL="https://127.0.0.1:${PORT}"
ENV_FILE="$OUT_DIR/fixture.env"
MONGO_ENV="$OUT_DIR/mongo.env"
MONGO_INIT="$OUT_DIR/init-mongo.js"
ADMIN_USER="labadmin"
# Fake, locally administered MACs standing in for poseidon and hercules-nas (fixture only).
# scripts/lab/unifi-fixture-plan.sh uses the same values.
FIXTURE_HOST_MACS="poseidon=02:00:00:00:01:01 hercules-nas=02:00:00:00:01:10"

log()  { printf '\n\033[1m== %s ==\033[0m\n' "$*"; }
note() { printf '   %s\n' "$*"; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "missing tool: docker"
command -v curl >/dev/null 2>&1 || die "missing tool: curl"
command -v openssl >/dev/null 2>&1 || die "missing tool: openssl"
case "$PORT" in ''|*[!0-9]*) die "LAB_UNIFI_PORT must be a number" ;; esac

exists()  { docker container inspect "$1" >/dev/null 2>&1; }
running() { [ "$(docker container inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" = true ]; }

# Everything below acts on the fixed names above, never on a name taken from outside.
for n in "$NAME" "$MONGO_NAME" "$NET" "$VOL_CONFIG" "$VOL_MONGO"; do
  case "$n" in lab-unifi*) : ;; *) die "refusing: '$n' does not carry the lab-unifi prefix" ;; esac
done

write_credentials() {
  mkdir -p "$OUT_DIR"
  chmod 700 "$OUT_DIR"
  local mongo_pass admin_pass
  mongo_pass="$(openssl rand -hex 16)"
  admin_pass="$(openssl rand -hex 12)"
  umask 077
  cat >"$MONGO_ENV" <<ENV
MONGO_USER=unifi
MONGO_PASS=$mongo_pass
MONGO_HOST=$MONGO_NAME
MONGO_PORT=27017
MONGO_DBNAME=unifi
MONGO_AUTHSOURCE=unifi
MEM_LIMIT=1024
MEM_STARTUP=512
ENV
  # Read by the mongo entrypoint as another user, so it has to be world-readable; the directory is 700.
  cat >"$MONGO_INIT" <<JS
db.getSiblingDB("unifi").createUser({user: "unifi", pwd: "$mongo_pass", roles: [{role: "dbOwner", db: "unifi"}, {role: "dbOwner", db: "unifi_stat"}, {role: "dbOwner", db: "unifi_audit"}]});
JS
  chmod 644 "$MONGO_INIT"
  cat >"$ENV_FILE" <<ENV
# Generated by scripts/lab/unifi-fixture.sh. Fixture only; never a real credential.
UNIFI_FIXTURE_URL=$URL
UNIFI_FIXTURE_USERNAME=$ADMIN_USER
UNIFI_FIXTURE_PASSWORD=$admin_pass
ENV
}

controller_up() { curl -sk --max-time 5 "$URL/status" 2>/dev/null | grep -q '"up":true'; }

login_ok() {
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  local body
  body="$(jq -nc --arg u "$UNIFI_FIXTURE_USERNAME" --arg p "$UNIFI_FIXTURE_PASSWORD" '{username:$u,password:$p}')"
  curl -sk --max-time 10 -X POST "$URL/api/login" -H 'content-type: application/json' -d "$body" \
    | grep -q '"rc":"ok"'
}

do_up() {
  log "fixture images"
  note "controller $UNIFI_IMAGE"
  note "mongo      $MONGO_IMAGE"
  for img in "$UNIFI_IMAGE" "$MONGO_IMAGE"; do
    docker image inspect "$img" >/dev/null 2>&1 || docker pull -q "$img" >/dev/null
  done

  log "credentials ($OUT_DIR, gitignored)"
  if [ -f "$ENV_FILE" ] && [ -f "$MONGO_ENV" ] && [ -f "$MONGO_INIT" ]; then
    note "reusing"
  else
    if docker volume inspect "$VOL_MONGO" >/dev/null 2>&1 || docker volume inspect "$VOL_CONFIG" >/dev/null 2>&1; then
      die "lab-unifi volumes exist but their credentials are gone; run: scripts/lab/unifi-fixture.sh down"
    fi
    write_credentials
    note "generated"
  fi

  log "network and volumes"
  docker network inspect "$NET" >/dev/null 2>&1 || docker network create "$NET" >/dev/null
  docker volume inspect "$VOL_MONGO" >/dev/null 2>&1 || docker volume create "$VOL_MONGO" >/dev/null
  docker volume inspect "$VOL_CONFIG" >/dev/null 2>&1 || docker volume create "$VOL_CONFIG" >/dev/null

  log "$MONGO_NAME (memory $MONGO_MEM, no published port)"
  if exists "$MONGO_NAME"; then
    running "$MONGO_NAME" || docker start "$MONGO_NAME" >/dev/null
    note "present"
  else
    docker run -d --name "$MONGO_NAME" --network "$NET" --memory "$MONGO_MEM" --memory-swap "$MONGO_MEM" \
      -v "$VOL_MONGO:/data/db" -v "$MONGO_INIT:/docker-entrypoint-initdb.d/init-mongo.js:ro" \
      "$MONGO_IMAGE" mongod --auth --wiredTigerCacheSizeGB 0.25 >/dev/null
    note "started"
  fi
  # The image's first start runs the init script, restarts mongod, and only then listens for real.
  for _ in $(seq 60); do
    docker exec "$MONGO_NAME" mongosh --quiet --eval 'db.runCommand({ping:1}).ok' >/dev/null 2>&1 && break
    sleep 2
  done

  log "$NAME (memory $MEM, published on 127.0.0.1:$PORT only)"
  if exists "$NAME"; then
    running "$NAME" || docker start "$NAME" >/dev/null
    note "present"
  else
    docker run -d --name "$NAME" --network "$NET" --memory "$MEM" --memory-swap "$MEM" \
      -p "127.0.0.1:${PORT}:8443" --env-file "$MONGO_ENV" -v "$VOL_CONFIG:/config" \
      "$UNIFI_IMAGE" >/dev/null
    note "started"
  fi

  log "waiting for the controller (first start takes a few minutes)"
  for _ in $(seq 120); do
    controller_up && break
    sleep 5
  done
  controller_up || die "controller did not come up; see: docker logs $NAME"
  note "up at $URL"

  log "first-run setup"
  command -v jq >/dev/null 2>&1 || die "missing tool: jq"
  if login_ok; then
    note "admin already exists"
  else
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    local body
    body="$(jq -nc --arg u "$UNIFI_FIXTURE_USERNAME" --arg p "$UNIFI_FIXTURE_PASSWORD" \
      '{cmd:"add-default-admin",name:$u,email:"labadmin@example.invalid",x_password:$p}')"
    curl -sk --max-time 30 -X POST "$URL/api/cmd/sitemgr" -H 'content-type: application/json' -d "$body" \
      | grep -q '"rc":"ok"' || die "creating the local admin failed"
    login_ok || die "created the admin but cannot log in"
    note "created local admin '$UNIFI_FIXTURE_USERNAME' (site 'default')"
  fi
  note "credentials: $ENV_FILE"

  seed_existing
}

# Pre-existing objects, created through the controller API and not through tofu, so the root meets
# them the way it meets the real controller: a server network to read, clients to take over.
seed_existing() {
  log "seed pre-existing objects (outside tofu)"
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  local jar api body
  jar="$(mktemp)"
  api="$URL/api/s/default"
  body="$(jq -nc --arg u "$UNIFI_FIXTURE_USERNAME" --arg p "$UNIFI_FIXTURE_PASSWORD" '{username:$u,password:$p}')"
  curl -sk --max-time 10 -c "$jar" -X POST "$URL/api/login" -H 'content-type: application/json' -d "$body" \
    | grep -q '"rc":"ok"' || { rm -f "$jar"; die "seed: login failed"; }

  if curl -sk --max-time 10 -b "$jar" "$api/rest/networkconf" | jq -e '.data[] | select(.name=="server")' >/dev/null; then
    note "network 'server' present"
  else
    curl -sk --max-time 10 -b "$jar" -X POST "$api/rest/networkconf" -H 'content-type: application/json' \
      -d '{"name":"server","purpose":"corporate","enabled":true,"vlan_enabled":true,"vlan":4,"ip_subnet":"10.10.0.1/16","networkgroup":"LAN","dhcpd_enabled":true,"dhcpd_start":"10.10.0.100","dhcpd_stop":"10.10.255.254","setting_preference":"manual"}' \
      | grep -q '"rc":"ok"' || { rm -f "$jar"; die "seed: creating network 'server' failed"; }
    note "created network 'server' (VLAN 4, 10.10.0.0/16)"
  fi

  local pair host mac
  for pair in $FIXTURE_HOST_MACS; do
    host="${pair%%=*}"
    mac="${pair#*=}"
    if curl -sk --max-time 10 -b "$jar" "$api/rest/user" | jq -e --arg m "$mac" '.data[] | select(.mac==$m)' >/dev/null; then
      note "client $mac ($host) present"
    else
      body="$(jq -nc --arg m "$mac" --arg n "$host" '{mac:$m,name:$n,note:"seeded outside tofu"}')"
      curl -sk --max-time 10 -b "$jar" -X POST "$api/rest/user" -H 'content-type: application/json' -d "$body" \
        | grep -q '"rc":"ok"' || { rm -f "$jar"; die "seed: creating client $mac failed"; }
      note "created client $mac ($host), no fixed IP"
    fi
  done
  rm -f "$jar"
}

do_status() {
  log "containers"
  docker ps -a --filter "name=^${NAME}" --format '   {{.Names}}  {{.Status}}  {{.Ports}}'
  log "controller"
  if controller_up; then
    note "up at $URL"
    if [ -f "$ENV_FILE" ] && command -v jq >/dev/null 2>&1; then
      if login_ok; then note "local admin login: ok"; else note "local admin login: FAILED"; fi
    fi
  else
    note "not responding on $URL"
  fi
  log "memory"
  docker stats --no-stream --format '   {{.Name}}  {{.MemUsage}}' "$NAME" "$MONGO_NAME" 2>/dev/null || true
}

do_stop() {
  log "stopping"
  for c in "$NAME" "$MONGO_NAME"; do
    if running "$c"; then docker stop "$c" >/dev/null; note "stopped $c"; fi
  done
}

do_down() {
  log "removing the fixture"
  for c in "$NAME" "$MONGO_NAME"; do
    if exists "$c"; then docker rm -f "$c" >/dev/null; note "removed $c"; fi
  done
  docker network inspect "$NET" >/dev/null 2>&1 && { docker network rm "$NET" >/dev/null; note "removed network $NET"; }
  for v in "$VOL_CONFIG" "$VOL_MONGO"; do
    docker volume inspect "$v" >/dev/null 2>&1 && { docker volume rm "$v" >/dev/null; note "removed volume $v"; }
  done
  rm -f "$ENV_FILE" "$MONGO_ENV" "$MONGO_INIT"
  note "removed credentials in $OUT_DIR"
  # The plan script's scratch state describes objects on the controller just removed; keeping it would
  # make the next run plan against IDs that no longer exist.
  if [ -d "$OUT_DIR/tofu" ]; then rm -rf "${OUT_DIR:?}/tofu"; note "removed scratch tofu state in $OUT_DIR/tofu"; fi
}

case "${1:-}" in
  up)     do_up ;;
  status) do_status ;;
  stop)   do_stop ;;
  down)   do_down ;;
  -h|--help|"") sed -n '2,28p' "$0"; [ -n "${1:-}" ] || exit 2 ;;
  *) die "unknown argument: $1" ;;
esac
