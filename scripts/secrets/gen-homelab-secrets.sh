#!/usr/bin/env bash
# gen-homelab-secrets.sh — write every Secret the PRODUCTION (`homelab`) cluster needs, SOPS-encrypted.
#
# The production counterpart of gen-lab-secrets.sh. Each Secret in the table in
# kubernetes/overlays/homelab/README.md lands in kubernetes/overlays/homelab/<layer>/<name>.sops.yaml and is
# added to that layer's kustomization.yaml. Passwords and keys are generated locally; values only the owner
# knows are prompted for without echo, or read from the environment for non-interactive use:
#   HOMELAB_CLOUDFLARE_API_TOKEN  Cloudflare token (Zone:DNS:Edit on the zone only)
#   HOMELAB_SMTP_PASSWORD         SMTP relay password (alertmanager-smtp, authentik-smtp, seafile-smtp)
#   HOMELAB_SEAFILE_ADMIN_EMAIL   first Seafile admin's email
#   HOMELAB_KOPIA_USERS           comma-separated <user>_<host> list, e.g. arthur_arthur-pc,dunia_dunia-pc
#   HOMELAB_CLOUDFLARED_CREDENTIALS_FILE  optional: tunnel credentials JSON file -> cloudflared-tunnel
# Plaintext only exists in a private temp dir and is piped into sops; it is never written into the
# repository and never printed. Refuses to run until .sops.yaml holds the production age recipient.
#
# An existing file is kept; --force rewrites it. Even with --force, the Secrets holding values that must
# never change after the first install (authentik-credentials, seafile-jwt, kopia-repository) are kept
# unless --rotate-immutable is also given: rotating them breaks Authentik, Seahub or every Kopia backup.
#
# Usage: scripts/secrets/gen-homelab-secrets.sh [--force [--rotate-immutable]] [--dry-run]
set -euo pipefail

# shellcheck source=SCRIPTDIR/common.sh
. "$(dirname "$0")/common.sh"

force=0
rotate_immutable=0
dry=0
for arg in "$@"; do
  case "$arg" in
    --force) force=1 ;;
    --rotate-immutable) rotate_immutable=1 ;;
    --dry-run) dry=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done
[ "$rotate_immutable" -eq 0 ] || [ "$force" -eq 1 ] || die "--rotate-immutable only makes sense with --force"

require sops yq
OVERLAY="$REPO_ROOT/kubernetes/overlays/homelab"
CONFIG="$REPO_ROOT/.sops.yaml"

[ -f "$CONFIG" ] || die "missing $CONFIG"
if grep -q 'REPLACE_WITH_PRODUCTION_AGE_RECIPIENT' "$CONFIG"; then
  die ".sops.yaml still has the production placeholder; do the key ceremony first (docs/runbooks/secrets.md §2)"
fi

tmp="$(mktemp -d)"
chmod 700 "$tmp"
trap 'rm -rf "$tmp"' EXIT

# rand [length] — alphanumeric, so it is safe in env vars, URLs and connection strings.
rand() {
  local n="${1:-40}" out=""
  while [ "${#out}" -lt "$n" ]; do
    out+="$(head -c 96 /dev/urandom | base64 -w0 | tr -dc 'A-Za-z0-9')"
  done
  printf '%s' "${out:0:$n}"
}

# immutable <name> — Secrets whose values must never change after the first install.
immutable() {
  case "$1" in
    authentik-credentials|seafile-jwt|kopia-repository) return 0 ;;
    *) return 1 ;;
  esac
}

# will_write <layer> <name> — true when this run (re)writes the Secret (dry-run included).
will_write() {
  local dest="$OVERLAY/$1/$2.sops.yaml"
  [ -e "$dest" ] || return 0
  [ "$force" -eq 1 ] || return 1
  immutable "$2" && [ "$rotate_immutable" -eq 0 ] && return 1
  return 0
}

# ask <var> <prompt> [visible] — fill <var> from the environment, else prompt (no echo unless `visible`).
# Skipped in --dry-run: nothing is written, so nothing is needed.
ask() {
  local var="$1" prompt="$2" visible="${3:-}" val
  [ "$dry" -eq 0 ] || return 0
  [ -z "${!var:-}" ] || return 0
  [ -t 0 ] || die "$var is not set and stdin is not a terminal"
  if [ -n "$visible" ]; then
    read -rp "$prompt: " val
  else
    read -rsp "$prompt (input hidden): " val
    printf '\n' >&2
  fi
  [ -n "$val" ] || die "$var must not be empty"
  printf -v "$var" '%s' "$val"
}

# secret <layer> <namespace> <name> <key>=<value>...
# A value of `@rand` or `@rand:<length>` is replaced with a random string. Values are written as
# single-quoted YAML scalars, so any character but a newline is safe.
secret() {
  local layer="$1" ns="$2" name="$3"
  shift 3
  local rel="$layer/$name.sops.yaml"
  local dest="$OVERLAY/$rel"

  if ! will_write "$layer" "$name"; then
    if [ -e "$dest" ] && [ "$force" -eq 1 ]; then
      note "keep    $rel (must never change; --rotate-immutable to override)"
    else
      note "keep    $rel"
    fi
  elif [ "$dry" -eq 1 ]; then
    note "[dry-run] write $rel (keys: ${*%%=*})"
  else
    local plain="$tmp/$name.yaml" kv k v
    {
      printf -- '---\n# Generated by scripts/secrets/gen-homelab-secrets.sh (kubernetes/overlays/homelab/README.md).\n'
      printf 'apiVersion: v1\nkind: Secret\nmetadata:\n  name: %s\n  namespace: %s\ntype: Opaque\nstringData:\n' "$name" "$ns"
      for kv in "$@"; do
        k="${kv%%=*}"
        v="${kv#*=}"
        case "$v" in
          @rand) v="$(rand)" ;;
          @rand:*) v="$(rand "${v#@rand:}")" ;;
        esac
        case "$v" in *$'\n'*|*$'\r'*) die "value for $name/$k contains a newline" ;; esac
        printf "  %s: '%s'\n" "$k" "${v//\'/\'\'}"
      done
    } >"$plain"
    # --filename-override makes .sops.yaml pick the production rule from the destination path.
    sops --config "$CONFIG" encrypt --filename-override "$dest" "$plain" >"$tmp/$name.enc"
    rm -f "$plain"
    mv "$tmp/$name.enc" "$dest"
    note "wrote   $rel"
  fi

  local entry="$name.sops.yaml" kust="$OVERLAY/$layer/kustomization.yaml"
  if ! yq -e ".resources[] | select(. == \"$entry\")" "$kust" >/dev/null 2>&1; then
    if [ "$dry" -eq 1 ]; then
      note "[dry-run] add $entry to $layer/kustomization.yaml"
    else
      yq -i ".resources += [\"$entry\"]" "$kust"
    fi
  fi
}

# Each OIDC client secret is one value in two Secrets (Authentik's and the app's), so both are written together
# or both kept. One without the other can't be repaired without the private key: stop before writing anything.
# Pairs: <layer>/<authentik Secret> <layer>/<app Secret>.
oidc_pair() {
  local a=0 b=0
  will_write "${1%%/*}" "${1#*/}" && a=1
  will_write "${2%%/*}" "${2#*/}" && b=1
  [ "$a" -eq "$b" ] || die "only one of ${1#*/} / ${2#*/} exists; rerun with --force to regenerate both"
}
oidc_pair apps/authentik-seafile-oidc apps/seafile-oidc
oidc_pair apps/authentik-grafana-oidc infrastructure/grafana-oidc

log "homelab secrets -> kubernetes/overlays/homelab"

# --- infrastructure ---------------------------------------------------------------------------
if will_write infrastructure cloudflare-api-token; then
  ask HOMELAB_CLOUDFLARE_API_TOKEN "Cloudflare API token (Zone:DNS:Edit)"
fi
secret infrastructure cert-manager cloudflare-api-token api-token="${HOMELAB_CLOUDFLARE_API_TOKEN:-}"
secret infrastructure monitoring grafana-admin admin-user=admin admin-password=@rand
# SMTP: one Secret per app namespace, all for the same relay login (docs/decisions.md §5.1).
if will_write infrastructure alertmanager-smtp || will_write apps authentik-smtp || will_write apps seafile-smtp; then
  ask HOMELAB_SMTP_PASSWORD "SMTP relay password"
fi
secret infrastructure monitoring alertmanager-smtp smtp-password="${HOMELAB_SMTP_PASSWORD:-}"
secret infrastructure technitium technitium-admin password=@rand
# OIDC client secret of Grafana's Authentik login: the SAME value as apps/authentik-grafana-oidc (checked above).
# grafana-oidc sits in the infrastructure layer with Grafana; the authentik namespace only exists in apps.
grafana_oidc="$(rand 48)"
secret infrastructure monitoring grafana-oidc client-secret="$grafana_oidc"

# --- apps -------------------------------------------------------------------------------------
secret apps immich immich-db username=immich password=@rand
# secret-key must never change after the first install (kubernetes/apps/authentik/release.yaml).
secret apps authentik authentik-credentials secret-key=@rand:60 postgres-password=@rand
secret apps authentik authentik-smtp smtp-password="${HOMELAB_SMTP_PASSWORD:-}"
# Seafile (kubernetes/apps/seafile): MariaDB root and app passwords, the first admin, the relay login
# and the JWT key seahub signs with (like authentik's secret-key, never change it after first install).
secret apps seafile seafile-db root-password=@rand password=@rand
if will_write apps seafile-admin; then
  ask HOMELAB_SEAFILE_ADMIN_EMAIL "Seafile admin email" visible
fi
secret apps seafile seafile-admin email="${HOMELAB_SEAFILE_ADMIN_EMAIL:-}" password=@rand
secret apps seafile seafile-smtp smtp-password="${HOMELAB_SMTP_PASSWORD:-}"
secret apps seafile seafile-jwt jwt-private-key=@rand:40
# OIDC client secret of Seafile's Authentik login: the SAME value in both namespaces (checked above).
seafile_oidc="$(rand 48)"
secret apps authentik authentik-seafile-oidc client-secret="$seafile_oidc"
secret apps seafile seafile-oidc client-secret="$seafile_oidc"
secret apps authentik authentik-grafana-oidc client-secret="$grafana_oidc"
# Immich and Audiobookshelf keep their client secret in their own database (docs/runbooks/sso.md): only
# Authentik's side is a Secret.
secret apps authentik authentik-immich-oidc client-secret=@rand:48
secret apps authentik authentik-audiobookshelf-oidc client-secret=@rand:48
# Proxmox and Technitium likewise keep theirs in their own configuration (pasted once, docs/runbooks/sso.md).
secret apps authentik authentik-proxmox-oidc client-secret=@rand:48
secret apps authentik authentik-technitium-oidc client-secret=@rand:48
# Kopia repository server (kubernetes/apps/kopia). The repository password is the only key to the
# backups; the server login is the UI/API, the control login is for the server's own control API,
# and kopia-users holds one password per client device, key `<user>_<host>` for user@host.
secret apps kopia kopia-repository password=@rand:40
secret apps kopia kopia-server username=admin password=@rand control-username=control control-password=@rand
kopia_users=()
if will_write apps kopia-users; then
  ask HOMELAB_KOPIA_USERS "Kopia devices, comma-separated <user>_<host> (e.g. arthur_arthur-pc)" visible
  IFS=',' read -ra devices <<<"${HOMELAB_KOPIA_USERS:-user_host}"
  for d in "${devices[@]}"; do
    d="${d// /}"
    [ -n "$d" ] || continue
    [[ "$d" =~ ^[A-Za-z0-9._-]+$ ]] || die "invalid kopia user key: $d (want <user>_<host>)"
    kopia_users+=("$d=@rand")
  done
  [ "${#kopia_users[@]}" -gt 0 ] || die "HOMELAB_KOPIA_USERS lists no devices"
fi
secret apps kopia kopia-users "${kopia_users[@]}"
# Cloudflare Tunnel credentials (kubernetes/apps/cloudflared, docs/runbooks/public-shares.md). Opt-in: only
# with HOMELAB_CLOUDFLARED_CREDENTIALS_FILE, the one-line JSON from
# `tofu output -raw tunnel_credentials_json` in a private temp file. The tunnel ID is read from it.
if [ -n "${HOMELAB_CLOUDFLARED_CREDENTIALS_FILE:-}" ]; then
  [ -f "$HOMELAB_CLOUDFLARED_CREDENTIALS_FILE" ] || die "HOMELAB_CLOUDFLARED_CREDENTIALS_FILE: no such file"
  command -v jq >/dev/null 2>&1 || die "missing required tool: jq"
  cf_creds="$(jq -ce 'select(.AccountTag and .TunnelID and .TunnelSecret)' "$HOMELAB_CLOUDFLARED_CREDENTIALS_FILE")" ||
    die "HOMELAB_CLOUDFLARED_CREDENTIALS_FILE is not tunnel credentials JSON (AccountTag, TunnelID, TunnelSecret)"
  cf_tunnel_id="$(jq -r '.TunnelID' <<<"$cf_creds")"
  secret apps cloudflared cloudflared-tunnel credentials.json="$cf_creds" tunnel-id="$cf_tunnel_id"
  unset cf_creds
fi

log "done. Check: scripts/secrets/check.sh --check && just k8s-validate"
[ "$dry" -eq 1 ] && exit 0
log "Read a value later with: scripts/secrets/decrypt.sh kubernetes/overlays/homelab/<layer>/<name>.sops.yaml"
log "  (needs the production key: SOPS_AGE_KEY_FILE=/path/to/prod-age.key)."
log "Keep an OFFLINE copy of the kopia-repository password: it is the only key to the backups."
