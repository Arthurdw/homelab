#!/usr/bin/env bash
# gen-lab-secrets.sh — write every Secret the LAB cluster needs, with random values, SOPS-encrypted.
#
# Each Secret lands in kubernetes/overlays/lab/<layer>/<name>.sops.yaml and is added to that overlay's
# kustomization.yaml (kubernetes/overlays/README.md). Plaintext only exists in a private temp dir and is
# piped into sops; it is never written into the repository.
#
# The values are disposable lab values: nothing outside the lab uses them. An existing file is left alone,
# so rerunning is safe; --force regenerates (the lab cluster then needs its stateful apps reset).
#
# Production Secrets are NOT created here: they need real values and the production age key
# (kubernetes/overlays/homelab/README.md, docs/runbooks/secrets.md).
#
# Usage: scripts/secrets/gen-lab-secrets.sh [--force] [--dry-run]
set -euo pipefail

# shellcheck source=SCRIPTDIR/common.sh
. "$(dirname "$0")/common.sh"

force=0
dry=0
for arg in "$@"; do
  case "$arg" in
    --force) force=1 ;;
    --dry-run) dry=1 ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

require sops yq
OVERLAY="$REPO_ROOT/kubernetes/overlays/lab"
CONFIG="$REPO_ROOT/.sops.yaml"

tmp="$(mktemp -d)"
chmod 700 "$tmp"
trap 'rm -rf "$tmp"' EXIT

# rand [length] — alphanumeric, so it is safe in env vars, URLs and connection strings.
rand() {
  local n="${1:-40}" out=""
  while [ "${#out}" -lt "$n" ]; do
    out+="$(head -c 96 /dev/urandom | base64 -w0 | tr -dc 'A-Za-z0-9')"
  done
  printf '%s' "${out:0:$n}"
}

# secret <layer> <namespace> <name> <key>=<value>...
# A value of `@rand` or `@rand:<length>` is replaced with a random string.
secret() {
  local layer="$1" ns="$2" name="$3"
  shift 3
  local rel="$layer/$name.sops.yaml"
  local dest="$OVERLAY/$rel"

  if [ -e "$dest" ] && [ "$force" -eq 0 ]; then
    note "keep    $rel"
  elif [ "$dry" -eq 1 ]; then
    note "[dry-run] write $rel (keys: ${*%%=*})"
  else
    local plain="$tmp/$name.yaml" kv k v
    {
      printf -- '---\n# Lab-only values, generated by scripts/secrets/gen-lab-secrets.sh.\n'
      printf 'apiVersion: v1\nkind: Secret\nmetadata:\n  name: %s\n  namespace: %s\ntype: Opaque\nstringData:\n' "$name" "$ns"
      for kv in "$@"; do
        k="${kv%%=*}"
        v="${kv#*=}"
        case "$v" in
          @rand) v="$(rand)" ;;
          @rand:*) v="$(rand "${v#@rand:}")" ;;
        esac
        printf '  %s: "%s"\n' "$k" "$v"
      done
    } >"$plain"
    # --filename-override makes .sops.yaml pick the lab rule from the destination path.
    sops --config "$CONFIG" encrypt --filename-override "$dest" "$plain" >"$tmp/$name.enc"
    mv "$tmp/$name.enc" "$dest"
    note "wrote   $rel"
  fi

  [ "$dry" -eq 1 ] && return 0
  local entry="$name.sops.yaml"
  if ! yq -e ".resources[] | select(. == \"$entry\")" "$OVERLAY/$layer/kustomization.yaml" >/dev/null 2>&1; then
    yq -i ".resources += [\"$entry\"]" "$OVERLAY/$layer/kustomization.yaml"
  fi
}

log "lab secrets -> kubernetes/overlays/lab"

# --- infrastructure ---------------------------------------------------------------------------
# SMTP passwords: one Secret per app namespace, all for the same relay login (docs/decisions.md §5.1). The
# lab never reaches the relay, so the values are dummies.
secret infrastructure monitoring alertmanager-smtp smtp-password=@rand
secret infrastructure monitoring grafana-admin admin-user=admin admin-password=@rand
secret infrastructure technitium technitium-admin password=@rand
# OIDC client secret of Grafana's Authentik login: the SAME value as apps/authentik-grafana-oidc below.
# grafana-oidc sits in the infrastructure layer with Grafana; the authentik namespace only exists in apps.
grafana_oidc="$(rand 48)"
secret infrastructure monitoring grafana-oidc client-secret="$grafana_oidc"

# --- apps -------------------------------------------------------------------------------------
secret apps immich immich-db username=immich password=@rand
# secret-key must never change after the first install (kubernetes/apps/authentik/release.yaml).
secret apps authentik authentik-credentials secret-key=@rand:60 postgres-password=@rand
secret apps authentik authentik-smtp smtp-password=@rand
# Seafile (kubernetes/apps/seafile): MariaDB root and app passwords, the first admin, the relay login
# and the JWT key seahub signs with (like authentik's secret-key, never change it after first install).
secret apps seafile seafile-db root-password=@rand password=@rand
secret apps seafile seafile-admin email=admin@lab.ardw.be password=@rand
secret apps seafile seafile-smtp smtp-password=@rand
secret apps seafile seafile-jwt jwt-private-key=@rand:40
# OIDC client secret of Seafile's Authentik login: the SAME value in both namespaces (Authentik's blueprint
# declares the client, Seafile presents it). Generated once per run; an existing file is kept.
seafile_oidc="$(rand 48)"
secret apps authentik authentik-seafile-oidc client-secret="$seafile_oidc"
secret apps seafile seafile-oidc client-secret="$seafile_oidc"
secret apps authentik authentik-grafana-oidc client-secret="$grafana_oidc"
# Immich and Audiobookshelf keep their client secret in their own database (docs/runbooks/sso.md): only
# Authentik's side is a Secret.
secret apps authentik authentik-immich-oidc client-secret=@rand:48
secret apps authentik authentik-audiobookshelf-oidc client-secret=@rand:48
# Kopia repository server (kubernetes/apps/kopia). The repository password is the only key to the
# backups; the server login is the UI/API, the control login is for the server's own control API,
# and kopia-users holds one password per client user, key `<user>_<host>` for user@host (test_lab here).
secret apps kopia kopia-repository password=@rand:40
secret apps kopia kopia-server username=admin password=@rand control-username=control control-password=@rand
secret apps kopia kopia-users test_lab=@rand

log "done. Check: scripts/secrets/check.sh --check && just k8s-validate"
